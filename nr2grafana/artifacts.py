def package_dashboard(out_dir: str, slug: str, dash: Dict[str, Any],
                      widget_report: List[Dict[str, Any]],
                      requirements: Dict[str, Any],
                      cfg: Dict[str, Any]) -> str:
    """Write <out_dir>/<slug>/ with dashboard.json, requirements.json,
    widget-report.json, README.md, datatest.json and an executable
    test.sh. Returns the package directory path."""
    pkg = os.path.join(out_dir, slug)
    os.makedirs(pkg, exist_ok=True)

    _write_json(os.path.join(pkg, "dashboard.json"), dash)
    _write_json(os.path.join(pkg, "requirements.json"), requirements or {})
    _write_json(os.path.join(pkg, "widget-report.json"), widget_report or [])
    _write_json(os.path.join(pkg, "datatest.json"),
                build_datatest(dash, widget_report or []))
    _write_text(os.path.join(pkg, "README.md"),
                render_readme(slug, dash, widget_report or [],
                              requirements or {}, cfg))
    test_sh = os.path.join(pkg, "test.sh")
    _write_text(test_sh, render_test_sh(dash.get("title") or slug))
    os.chmod(test_sh, 0o755)
    return pkg


def _index_row(entry: Dict[str, Any]) -> Tuple[str, ...]:
    req = entry.get("requirements") or {}
    report = entry.get("widget_report") or entry.get("report") or []
    title = (entry.get("title") or req.get("dashboard")
             or entry.get("slug") or "?")
    pkg_dir = (entry.get("dir") or entry.get("package_dir")
               or entry.get("slug") or "")
    dirname = os.path.basename(str(pkg_dir).rstrip("/"))
    counts = (entry.get("counts") or entry.get("confidence")
              or _confidence_counts(report))
    panels = entry.get("panels")
    if not isinstance(panels, int):
        panels = len(report) or sum(counts.values())
    datasources = entry.get("datasources")
    if not datasources:
        datasources = [d.get("family", "") for d in
                       req.get("datasources") or []]
    datasources = [str(d) for d in datasources if d]
    domains = entry.get("domains")
    if not domains:
        domains = [d.get("domain", "") for d in req.get("domains") or []]
    domains = [str(d) for d in domains if d]
    link = "[`%s/`](%s/README.md)" % (dirname, dirname) if dirname else ""
    return (
        _md_cell(title), link, str(panels),
        str(counts.get("exact", 0)), str(counts.get("approximate", 0)),
        str(counts.get("needs-review", 0)),
        str(counts.get("untranslatable", 0)),
        _md_cell(", ".join(datasources) or "-"),
        _md_cell(", ".join(domains) or "-"),
    )


def write_index(out_dir: str, entries: List[Dict[str, Any]]) -> str:
    """Write <out_dir>/INDEX.md summarizing all packaged dashboards.
    Returns the index file path."""
    lines = [
        "# Migration index",
        "",
        "Generated by nr2grafana. Each directory below is a",
        "self-contained package for one dashboard:",
        "",
        "- `dashboard.json` -- import this into Grafana",
        "- `README.md` / `requirements.json` -- what must exist first",
        "  (datasources, plugins, data pipelines) and how to import",
        "- `widget-report.json` -- per-panel translation confidence",
        "- `test.sh` + `datatest.json` -- live per-query data smoke test",
        "",
        "Suggested workflow per dashboard:",
        "",
        "1. Read `<dir>/README.md`; create the required datasources.",
        "2. Import `dashboard.json` (UI paste, or the curl in the README).",
        "3. `GRAFANA_URL=... GRAFANA_TOKEN=... sh <dir>/test.sh`",
        "4. Fix panels flagged needs-review/untranslatable, fold the fixes",
        "   into the converter config, reconvert.",
        "",
        "| Dashboard | Package | Panels | Exact | Approx | Review "
        "| Manual | Datasources | Domains |",
        "|---|---|--:|--:|--:|--:|--:|---|---|",
    ]
    for entry in entries or []:
        lines.append("| " + " | ".join(_index_row(entry)) + " |")
    if not entries:
        lines.append("| _no dashboards packaged_ | | | | | | | | |")
    path = os.path.join(out_dir, "INDEX.md")
    os.makedirs(out_dir, exist_ok=True)
    _write_text(path, "\n".join(lines))
    return path
