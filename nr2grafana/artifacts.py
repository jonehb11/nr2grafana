"""Per-dashboard artifact packages.

package_dashboard() writes one self-contained directory per converted
dashboard with everything a Grafana operator needs for a copy-paste
import that just works: the dashboard JSON, the machine-readable
requirements/widget reports, a human README (datasources to create,
plugins to install, import steps, troubleshooting), plus a data smoke
test (datatest.json manifest + executable test.sh runner).

write_index() summarizes all packages of one run into <out>/INDEX.md.
"""

from __future__ import annotations

import json
import os
from typing import Any, Dict, List, Optional, Tuple

from .livecheck import iter_targets

SCHEMA_DATATEST = "nr2grafana/datatest/v1"

CONFIDENCES = ("exact", "approximate", "needs-review", "untranslatable")

# Keys a query expression may live under, per datasource family (see
# grafana/builder._make_targets): prometheus/loki use "expr", tempo uses
# "query" (TraceQL), the New Relic passthrough plugin uses "queryText".
_EXPR_KEYS = ("expr", "query", "queryText")


# ---------------------------------------------------------------------------
# small helpers
# ---------------------------------------------------------------------------

def _family(ds_type: str) -> str:
    """Map a target's datasource plugin type to a datasource family."""
    t = (ds_type or "").lower()
    if "newrelic" in t:
        return "newrelic"
    if t in ("prometheus", "loki", "tempo"):
        return t
    return t or "prometheus"


def _md_cell(text: Any) -> str:
    """Make a value safe inside a markdown table cell."""
    s = str(text if text is not None else "")
    return s.replace("|", "\\|").replace("\n", " ").strip()


def _write_json(path: str, data: Any) -> None:
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, indent=2, ensure_ascii=True)
        f.write("\n")


def _write_text(path: str, text: str) -> None:
    if not text.endswith("\n"):
        text += "\n"
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def _confidence_counts(report: List[Dict[str, Any]]) -> Dict[str, int]:
    counts = {c: 0 for c in CONFIDENCES}
    for entry in report or []:
        c = entry.get("confidence", "")
        if c in counts:
            counts[c] += 1
    return counts


def _widget_label(entry: Dict[str, Any]) -> str:
    """Widget title from a report entry (both key spellings)."""
    return (entry.get("widget_title") or entry.get("widget")
            or "(untitled)")


# ---------------------------------------------------------------------------
# datatest.json
# ---------------------------------------------------------------------------

def build_datatest(dash: Dict[str, Any],
                   widget_report: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Machine manifest of per-panel test queries (raw exprs, no
    variable substitution) for grafana/live.py and test.sh."""
    conf_by_id: Dict[Any, str] = {}
    for entry in widget_report or []:
        conf_by_id[entry.get("panel_id")] = entry.get("confidence", "")

    targets: List[Dict[str, Any]] = []
    for panel, tgt in iter_targets(dash):
        expr = ""
        for key in _EXPR_KEYS:
            val = tgt.get(key)
            if isinstance(val, str) and val.strip():
                expr = val
                break
        if not expr:
            continue
        ds = tgt.get("datasource") or {}
        confidence = conf_by_id.get(panel.get("id"), "")
        targets.append({
            "panel_id": panel.get("id"),
            "panel_title": panel.get("title") or "",
            "refId": tgt.get("refId") or "A",
            "datasource_family": _family(ds.get("type", "")),
            "ds_uid_ref": ds.get("uid", ""),
            "expr": expr,
            "expect": ("data" if confidence in ("exact", "approximate")
                       else "any"),
        })
    return {
        "schema": SCHEMA_DATATEST,
        "dashboard": dash.get("title", ""),
        "uid": dash.get("uid", ""),
        "targets": targets,
    }


