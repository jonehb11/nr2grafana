# POSIX sh + curl + an embedded python3 helper (stdlib only, no jq).
# @TITLE@ is replaced at package time.
_TEST_SH = r'''#!/bin/sh
# Data smoke test for "@TITLE@" -- generated by nr2grafana.
#
# Runs every query in datatest.json against a live Grafana instance via
# POST /api/ds/query, resolving the datasource by type from
# GET /api/datasources (first datasource of the matching type wins).
#
# Usage:
#   GRAFANA_URL=https://grafana.example.com GRAFANA_TOKEN=glsa_... sh test.sh
#
# Output, one line per query:
#   PASS     query ran and returned data
#   NO-DATA  query ran but returned nothing (warning: metric/labels may
#            not exist in your stack yet -- see README troubleshooting)
#   FAIL     Grafana rejected the query or the request errored
# Exit code: 1 if any query FAILed, else 0. NO-DATA never fails the run.
#
# Needs: curl, python3 (used to read datatest.json -- no jq required).

set -u

DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
MANIFEST="$DIR/datatest.json"

if [ -z "${GRAFANA_URL:-}" ] || [ -z "${GRAFANA_TOKEN:-}" ]; then
    echo "error: set GRAFANA_URL and GRAFANA_TOKEN first, e.g." >&2
    echo "  GRAFANA_URL=https://grafana.example.com \\" >&2
    echo "  GRAFANA_TOKEN=glsa_xxx sh $0" >&2
    echo "(GRAFANA_TOKEN is a Grafana service account token)" >&2
    exit 2
fi
GRAFANA_URL=${GRAFANA_URL%/}

command -v curl >/dev/null 2>&1 || { echo "error: curl not found" >&2
    exit 2; }
command -v python3 >/dev/null 2>&1 || {
    echo "error: python3 not found (needed to read datatest.json)" >&2
    exit 2; }
[ -f "$MANIFEST" ] || { echo "error: $MANIFEST not found" >&2; exit 2; }

HELPER=$(cat <<'PYEOF'
import json, re, sys

TYPE_OF = {"prometheus": "prometheus", "loki": "loki", "tempo": "tempo"}


def load(path):
    with open(path) as f:
        return json.load(f)


def targets(path):
    return load(path).get("targets") or []


def subst(expr):
    """Grafana template vars -> concrete values so queries parse.

    Equality matchers on variables become match-alls so panels that
    filter on a variable can still find data.
    """
    subs = [
        (r'=\s*"\$\{[A-Za-z_][A-Za-z0-9_:]*\}"', '=~".+"'),
        (r'=\s*"\$[A-Za-z_][A-Za-z0-9_]*"', '=~".+"'),
        (r'"\$\{[A-Za-z_][A-Za-z0-9_:]*\}"', '".+"'),
        (r'"\$[A-Za-z_][A-Za-z0-9_]*"', '".+"'),
        (r"\$__rate_interval", "5m"),
        (r"\$__interval", "1m"),
        (r"\$__range", "1h"),
        (r"\$__auto", "5m"),
        (r"\$\{[A-Za-z_][A-Za-z0-9_:]*\}", "x"),
        (r"\$[A-Za-z_][A-Za-z0-9_]*", "x"),
    ]
    for pat, rep in subs:
        expr = re.sub(pat, rep, expr)
    return expr


def resolve(dsfile, fam):
    """First datasource of the matching type -> (uid, type)."""
    try:
        dss = load(dsfile)
    except Exception:
        return None, None
    if not isinstance(dss, list):
        return None, None
    for ds in dss:
        t = (ds.get("type") or "").lower()
        if fam == "newrelic":
            if "newrelic" in t:
                return ds.get("uid"), ds.get("type")
        elif t == TYPE_OF.get(fam, fam):
            return ds.get("uid"), ds.get("type")
    return None, None


def cmd_count(manifest):
    print(len(targets(manifest)))


def cmd_line(manifest, i):
    t = targets(manifest)[int(i)]
    title = (t.get("panel_title") or "").replace("|", "/")
    print("|".join([str(t.get("panel_id")), t.get("refId") or "A",
                    t.get("datasource_family") or "", title]))


def cmd_body(manifest, dsfile, i):
    t = targets(manifest)[int(i)]
    fam = t.get("datasource_family") or "prometheus"
    uid, dstype = resolve(dsfile, fam)
    if not uid:
        sys.stderr.write(
            "no %s datasource on this Grafana instance; add one under "
            "Connections -> Data sources\n" % fam)
        sys.exit(3)
    expr = subst(t.get("expr") or "")
    q = {"refId": t.get("refId") or "A",
         "datasource": {"type": dstype, "uid": uid}}
    if fam == "tempo":
        q.update({"queryType": "traceql", "query": expr, "limit": 20})
    elif fam == "loki":
        q.update({"expr": expr, "queryType": "range", "maxLines": 20})
    elif fam == "newrelic":
        q.update({"queryText": t.get("expr") or "",
                  "useGrafanaTime": True})
    else:
        q.update({"expr": expr, "format": "time_series", "range": True,
                  "instant": False, "intervalMs": 60000,
                  "maxDataPoints": 200})
    print(json.dumps({"queries": [q], "from": "now-1h", "to": "now"}))


def cmd_check(respfile, refid, http_code):
    try:
        body = load(respfile)
    except Exception:
        print("FAIL no JSON response from Grafana (HTTP %s)" % http_code)
        return
    if not isinstance(body, dict) or "results" not in body:
        msg = ""
        if isinstance(body, dict):
            msg = body.get("message") or ""
        print("FAIL %s" % (msg or "HTTP %s" % http_code)[:200])
        return
    res = body["results"].get(refid)
    if res is None:
        vals = list(body["results"].values())
        res = vals[0] if vals else {}
    err = res.get("error") or ""
    if err:
        print("FAIL %s" % str(err)[:200])
        return
    frames = res.get("frames") or []
    points = 0
    for fr in frames:
        for col in ((fr.get("data") or {}).get("values") or []):
            points += len(col or [])
    if points:
        print("PASS")
    else:
        print("NO-DATA")


CMDS = {"count": cmd_count, "line": cmd_line, "body": cmd_body,
        "check": cmd_check}
CMDS[sys.argv[1]](*sys.argv[2:])
PYEOF
)

WORK=$(mktemp -d) || exit 2
trap 'rm -rf "$WORK"' EXIT INT TERM

DSFILE="$WORK/datasources.json"
code=$(curl -sS -m 30 -o "$DSFILE" -w '%{http_code}' \
    -H "Authorization: Bearer $GRAFANA_TOKEN" \
    "$GRAFANA_URL/api/datasources") || {
    echo "error: cannot reach $GRAFANA_URL -- check the URL and network" >&2
    exit 1
}
case "$code" in
    200) ;;
    401|403)
        echo "error: Grafana rejected the token (HTTP $code)." >&2
        echo "Use a service account token with at least Viewer role." >&2
        exit 1 ;;
    *)
        echo "error: GET /api/datasources returned HTTP $code" >&2
        exit 1 ;;
esac

n=$(python3 -c "$HELPER" count "$MANIFEST") || {
    echo "error: could not read $MANIFEST" >&2; exit 2; }
if [ "$n" -eq 0 ]; then
    echo "nothing to test: datatest.json lists no queries"
    exit 0
fi

echo "Testing $n queries against $GRAFANA_URL ..."
pass=0; nodata=0; fail=0
i=0
while [ "$i" -lt "$n" ]; do
    line=$(python3 -c "$HELPER" line "$MANIFEST" "$i")
    pid=${line%%|*};  rest=${line#*|}
    refid=${rest%%|*}; rest=${rest#*|}
    fam=${rest%%|*};  title=${rest#*|}
    label="panel $pid [$refid] ($fam) $title"

    if body=$(python3 -c "$HELPER" body "$MANIFEST" "$DSFILE" "$i" \
            2>"$WORK/err"); then
        code=$(printf '%s' "$body" | curl -sS -m 60 -o "$WORK/resp.json" \
            -w '%{http_code}' \
            -H "Authorization: Bearer $GRAFANA_TOKEN" \
            -H "Content-Type: application/json" \
            -X POST "$GRAFANA_URL/api/ds/query" -d @-) || code=000
        verdict=$(python3 -c "$HELPER" check "$WORK/resp.json" \
            "$refid" "$code")
    else
        verdict="FAIL $(cat "$WORK/err")"
    fi

    case "$verdict" in
        PASS*)    pass=$((pass + 1));     echo "PASS     $label" ;;
        NO-DATA*) nodata=$((nodata + 1)); echo "NO-DATA  $label" ;;
        *)        fail=$((fail + 1));     echo "FAIL     $label"
                  echo "         ${verdict#FAIL }" ;;
    esac
    i=$((i + 1))
done

echo
echo "result: $pass passed, $nodata no-data, $fail failed (of $n)"
if [ "$fail" -gt 0 ]; then
    exit 1
fi
exit 0
'''


def render_test_sh(title: str) -> str:
    safe = (title or "dashboard").replace("\n", " ").replace('"', "'")
    return _TEST_SH.replace("@TITLE@", safe)


