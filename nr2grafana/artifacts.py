def _readme_datasources(req: Dict[str, Any]) -> List[str]:
    lines: List[str] = ["### Required datasources", ""]
    dss = req.get("datasources") or []
    if not dss:
        lines.append("_None -- the dashboard has no live queries._")
        lines.append("")
        return lines
    lines += [
        "| Name | Plugin id | Core | Purpose | Referenced as |",
        "|---|---|---|---|---|",
    ]
    for ds in dss:
        fam = ds.get("family", "")
        lines.append("| %s | `%s` | %s | %s | `%s` |" % (
            _md_cell(fam.capitalize() or "?"),
            _md_cell(ds.get("plugin_id") or fam),
            "yes" if ds.get("core") else "no",
            _md_cell(ds.get("purpose") or ""),
            _md_cell(ds.get("uid_ref") or "")))
    lines += [
        "",
        "To add one in the Grafana UI: **Connections -> Data sources ->",
        "Add new data source**, pick the plugin above, set the URL of your",
        "backend (Mimir/Prometheus, Loki, Tempo, ...), then **Save & test**.",
        "The dashboard references datasources through template variables,",
        "so your datasource names do not need to match anything -- you pick",
        "them at import time.",
        "",
    ]
    return lines


def _readme_plugins(req: Dict[str, Any]) -> List[str]:
    plugins = req.get("plugins") or []
    if not plugins:
        return []
    lines = ["### Plugins to install", ""]
    for p in plugins:
        pid = p.get("id", "")
        reason = p.get("reason") or ""
        cmd = p.get("grafana_cli") or (
            "grafana-cli plugins install %s" % pid)
        lines.append("- `%s`%s" % (pid, (" -- " + reason) if reason else ""))
        lines += ["", "  ```sh", "  %s" % cmd, "  ```", ""]
    lines.append("Restart Grafana after installing plugins.")
    lines.append("")
    return lines


def _readme_domains(req: Dict[str, Any]) -> List[str]:
    domains = req.get("domains") or []
    if not domains:
        return []
    lines = [
        "### Data domains detected",
        "",
        "The source dashboard uses New Relic data that maps to these",
        "domains. Each needs a matching data pipeline or datasource on",
        "your side before the panels show data:",
        "",
    ]
    for d in domains:
        pids = ", ".join(str(p) for p in d.get("panel_ids") or [])
        lines.append("- **%s**%s" % (
            d.get("domain", "?"),
            (" (panels %s)" % pids) if pids else ""))
        for ev in (d.get("evidence") or [])[:3]:
            lines.append("  - evidence: `%s`" % _md_cell(ev))
        for opt in d.get("options") or []:
            kind = opt.get("kind", "option")
            note = opt.get("note") or ""
            plug = opt.get("plugin_id")
            extra = (" (`%s`)" % plug) if plug else ""
            lines.append("  - %s%s: %s" % (kind, extra, note))
    lines.append("")
    return lines


def _readme_nr_native(req: Dict[str, Any],
                      report: List[Dict[str, Any]]) -> List[str]:
    native = req.get("nr_native") or []
    if not native:
        return []
    titles = {e.get("panel_id"): _widget_label(e) for e in report or []}
    lines = [
        "## New Relic-native widgets",
        "",
        "These widgets have no direct LGTM equivalent as-is; each is",
        "listed with its closest option(s):",
        "",
    ]
    for w in native:
        pid = w.get("panel_id")
        title = titles.get(pid, "")
        head = "- Panel %s%s (`%s`)" % (
            pid, (" %r" % title) if title else "", w.get("widget", "?"))
        lines.append(head)
        if w.get("why"):
            lines.append("  - why: %s" % w["why"])
        if w.get("equivalent"):
            lines.append("  - equivalent: %s" % w["equivalent"])
    lines.append("")
    return lines


def _readme_import(req: Dict[str, Any]) -> List[str]:
    lines = ["## Import", "", "### Grafana UI", ""]
    steps = (req.get("import") or {}).get("steps") or []
    if steps:
        for i, step in enumerate(steps):
            s = str(step).strip()
            # steps may already be numbered ("1. ...")
            if s[:1].isdigit() and "." in s[:4]:
                lines.append(s)
            else:
                lines.append("%d. %s" % (i + 1, s))
    else:
        lines += [
            "1. Create the required datasources above.",
            "2. **Dashboards -> New -> Import**.",
            "3. Paste the contents of `dashboard.json` (or upload the "
            "file) and click **Load**.",
            "4. When prompted, pick a datasource for each variable, then "
            "**Import**.",
        ]
    lines += [
        "",
        "### Grafana API",
        "",
        "From this directory, with a service account token:",
        "",
        "```sh",
        "export GRAFANA_URL=https://grafana.example.com",
        "export GRAFANA_TOKEN=glsa_...   # service account token",
        "curl -sS -X POST \"$GRAFANA_URL/api/dashboards/db\" \\",
        "  -H \"Authorization: Bearer $GRAFANA_TOKEN\" \\",
        "  -H \"Content-Type: application/json\" \\",
        "  -d \"{\\\"dashboard\\\": $(cat dashboard.json), "
        "\\\"overwrite\\\": false, \\\"folderUid\\\": \\\"\\\"}\"",
        "```",
        "",
        "Keep `overwrite: false` for the first import (a title collision",
        "then fails loudly instead of replacing another dashboard); switch",
        "to `true` only when re-importing this same dashboard.",
        "",
    ]
    return lines


def _readme_troubleshooting(req: Dict[str, Any]) -> List[str]:
    lines = [
        "## Troubleshooting",
        "",
        "**Import prompts for datasources** -- expected. The dashboard",
        "references datasources through template variables; pick your",
        "Prometheus/Mimir, Loki and Tempo instances when asked. If a",
        "dropdown is empty, the matching datasource does not exist yet",
        "(see the table above).",
        "",
        "**Panels show \"No data\"** -- the query is valid but nothing in",
        "your stack matches it yet. Each panel expects specific",
        "metrics/labels or log streams:",
        "",
    ]
    expectations = req.get("data_expectations") or []
    for exp in expectations:
        needs = exp.get("needs") or {}
        parts = []
        metrics = needs.get("metrics") or []
        labels = needs.get("labels") or []
        selector = needs.get("stream_selector") or ""
        if metrics:
            parts.append("metrics " + ", ".join(
                "`%s`" % m for m in metrics))
        if selector:
            parts.append("log stream `%s`" % _md_cell(selector))
        if labels:
            parts.append("labels " + ", ".join(
                "`%s`" % l for l in labels))
        lines.append("- panel %s (%s): needs %s" % (
            exp.get("panel_id"), exp.get("datasource", "?"),
            "; ".join(parts) or "(see widget-report.json)"))
    if not expectations:
        lines.append("- see `requirements.json` (`data_expectations`) "
                     "and `widget-report.json`")
    lines += [
        "",
        "Common no-data causes: the OTel collector/exporter does not emit",
        "those metrics yet, your stack uses different label names (fix via",
        "`label_map`/`metric_map` in the converter config and reconvert),",
        "or the selected time range is empty.",
        "",
        "**Verify with the bundled smoke test** -- runs every panel query",
        "against your Grafana and prints PASS / NO-DATA / FAIL per query:",
        "",
        "```sh",
        "GRAFANA_URL=https://grafana.example.com GRAFANA_TOKEN=glsa_... \\",
        "  sh test.sh",
        "```",
        "",
        "FAIL lines mean Grafana rejected the query (bad datasource,",
        "missing plugin, or a query needing manual review); NO-DATA lines",
        "are warnings only. `datatest.json` is the machine-readable",
        "manifest behind `test.sh`.",
    ]
    return lines


def render_readme(slug: str, dash: Dict[str, Any],
                  widget_report: List[Dict[str, Any]],
                  requirements: Dict[str, Any],
                  cfg: Optional[Dict[str, Any]] = None) -> str:
    req = requirements or {}
    report = widget_report or []
    title = dash.get("title") or req.get("dashboard") or slug
    counts = _confidence_counts(report)

    lines: List[str] = [
        "# %s" % title,
        "",
        "Converted from the New Relic dashboard \"%s\" by %s." % (
            req.get("dashboard") or title,
            req.get("generated_by") or "nr2grafana"),
        "",
        "- Grafana UID: `%s`" % dash.get("uid", ""),
        "- Package: `%s/`" % slug,
        "- Panels with queries: %d" % len(report),
        "",
        "## Panel confidence",
        "",
        "| Confidence | Panels | Meaning |",
        "|---|--:|---|",
        "| exact | %d | semantically equivalent |" % counts["exact"],
        "| approximate | %d | close; minor semantic drift |"
        % counts["approximate"],
        "| needs-review | %d | translated but verify by hand "
        "(`[REVIEW]` in title) |" % counts["needs-review"],
        "| untranslatable | %d | placeholder or NR passthrough "
        "(`[MANUAL]` in title) |" % counts["untranslatable"],
        "",
    ]
    flagged = [e for e in report
               if e.get("confidence") in ("needs-review", "untranslatable")]
    if flagged:
        lines.append("Panels to review:")
        lines.append("")
        for e in flagged:
            lines.append("- panel %s %r (%s)" % (
                e.get("panel_id"), _widget_label(e),
                e.get("confidence")))
        lines.append("")

    lines += ["## Before you import", ""]
    lines += _readme_datasources(req)
    lines += _readme_plugins(req)
    lines += _readme_domains(req)
    lines += _readme_nr_native(req, report)
    lines += _readme_import(req)
    lines += _readme_troubleshooting(req)
    return "\n".join(lines) + "\n"


